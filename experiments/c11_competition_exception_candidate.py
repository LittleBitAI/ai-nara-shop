#     `입찰`·`방식` 바로 뒤 조사만 보므로 "경쟁입찰 외의 방법으로" · "경쟁입찰의 방법 등으로는" ·
#     "경쟁입찰의 예외" 는 안 걸린다.
#   자격 — 중소기업·소기업·소상공인이 나오고 **같은 문장 40자 안에** 한정 표지(`만 참가` ·
#     `에 한함` · `로 제한/한정`)가 온다. 사이 말은 보지 않는다 — `중소기업확인서를 소지한
#     업체만 참가` · `중소기업(비영리 제외)에 한함` 처럼 한정을 적는 방법이 끝이 없어서다.
# 이 거부 전체가 dev 6건 · 무라벨 766건에 걸리고, C11 이 발화하는 18건(dev 1 · 무라벨 17)과는
# 하나도 겹치지 않는다.
SME_ONLY_BID = re.compile(
    r"중소기업자\s*간\s*경쟁(\s*입찰)?\s*(방식|방법)?\s*(으로|로|을|를)\s*(진행|실시|집행|추진|시행|입찰|한다|합니다|함)"
    r"|중소기업자\s*간\s*경쟁\s*입찰\s*대상(입니다|이다|임)"
    r"|(입찰|계약|낙찰)\s*(방법|방식)\s*[:：]?\s*(\S+\s*)?중소기업자\s*간\s*(제한\s*)?경쟁"
    r"(?!\s*(입찰|제품)?\s*(의|에\s*대한|외|적용\s*제외))"
    r"|(중소기업|소기업|소상공인)[^.。※]{0,40}?"
    r"(만\s*(이\s*)?(입찰|참가|참여|응찰|가능|을\s*대상)|에\s*한(함|합니다|한다|하며|하여|하고|정|해)|(으)?로\s*(제한|한정))")
# 같은 효과를 부정문으로 적는 꼴 — "중소기업자간 경쟁입찰 제품에 해당하지 않음"(실제 공고
# `PPS-D-018502`). 여기서 부정은 예외를 **긍정**한다. 그래서 이 꼴의 `않` 은 `NEGATED` 로
# 보지 않고, 그 **앞**의 부정·조건만 본다.
NOT_SME_BID = re.compile(
    r"중소기업자\s*간\s*경쟁\s*입찰\s*(제품|대상)?에\s*해당하지\s*(않|아니)(음|습니다|는다|함)" + _END)
# 부정은 **예외 판단의 범위 안에서만** 본다 — 인용 끝부터 적용 서술어 끝까지. 서술어 자체의
# 부정(`적용하지 않`·`안 적용`·`미적용`·`예외 적용 불가`)은 `APPLIED` 가 애초에 안 받는다.
# 남는 것은 서술어 **앞**의 부정이다 — "예외에 해당하지 않으므로 일반 규정을 적용합니다".
# 서술어 **뒤**의 부정은 결과의 서술이다 — "적용하므로 대기업의 참여 제한이 없습니다".
NEGATED = re.compile(r"않|아니|없|못|불가|불허|배제|[안미]\s*(적용|해당)")
SENTENCE = 160


def baseline():
    """재생기가 읽은 제출 코드를 집는다. 단독 import 면 저장소 루트의 것을 읽는다."""
    submitted = sys.modules.get("submission")
    if submitted is not None:
        return submitted
    spec = importlib.util.spec_from_file_location("baseline_script", ROOT / "script.py")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def competition_exception(rec: dict[str, Any]) -> bool:
    """공고가 시행령 제7조제1항의 예외를 적용했다고 적는가.

    문서 전문을 본다. 제2항이 요구하는 기재는 공고문 어디에나 올 수 있고, 프롬프트
    예산(16,000자)에 잘린 뒤쪽에 있을 수도 있다. 이 규칙은 모델이 본 것이 아니라
    **제공된 입력**을 읽는다. 인용만 있고 적용한다는 말이 없거나 부정하면 `False` 다.
    """
    texts = [re.sub(r"\s+", " ", doc.get("text") or "") for doc in rec.get("docs") or []]
    if any(SME_ONLY_BID.search(text) for text in texts):
        return False
    for text in texts:
        for match in EXCEPTION.finditer(text):
            clause = re.split(r"[.※]", text[match.end():match.end() + SENTENCE], maxsplit=1)[0]
            for found in APPLIED.finditer(clause):
                if NEGATED.search(clause[:found.end()]) is None and asserted(clause, found):
                    return True
            for found in ELIGIBLE.finditer(clause):
                # 앞에 조건이 있으면("…에 해당하는 경우 대기업도 …") 가정이다.
                if NEGATED.search(clause[:found.end()]) is None and MODAL.search(clause[:found.start()]) is None:
                    return True
            for found in NOT_SME_BID.finditer(clause):
                head = clause[:found.start()]
                if NEGATED.search(head) is None and MODAL.search(head) is None:
                    return True
    return False


def asserted(clause: str, found: re.Match) -> bool:
    """`하여` 로 이어지면 뒤 절이 평서로 끝나야 한다. 서법 구문이 있으면 입찰 당사자가 그보다
    먼저 새 주어로 서고, 문장이 그 당사자 행위의 가능으로 끝날 때만 적용 서술이다."""
    if MANNER not in (found.group("e1"), found.group("e2")):
        return True
    rest = clause[found.end():]
    if DECLARATIVE_END.search(rest) is None:
        return False
    modal = MODAL.search(rest)
    if modal is None:
        return True
    # 끝의 당사자 가능이 **유일한** 서법이어야 한다. 그 앞에 조건·의문·목적이 하나라도 있으면
    # ("대기업도 참여할 수 있으면 …") 적용은 가정일 뿐이다.
    end = BIDDER_POSSIBLE_END.search(rest)
    if end is None:
        return False
    body = rest[:end.start()]
    return SUBJECT.search(body) is not None and MODAL.search(body) is None


def postprocess(parsed: dict[str, Any], rec: dict[str, Any]):
    """운영 후처리를 낸 뒤, 예외 공고의 네 항목만 0 으로 닫는다.

    닫기만 한다. 0 을 1 로 만들지 않는다. 근거문구는 비운다.
    """
    script = baseline()
    out = script.postprocess(parsed, rec)
    if not competition_exception(rec):
        return out
    for item in ITEMS:
        cell = out.get(item)
        if cell and cell.get("위반여부") == 1:
            out[item] = {"위반여부": 0, "근거문구": None}
    return out
