# 예외가 아니다. 어미는 완결형만(`가능한 경우`·`있으면` 은 안 받는다), `불가능` 은 뺀다.
NON_SME = r"(대기업|중견기업|비영리\s*(법인|단체)|대·중견기업)"
ELIGIBLE = re.compile(
    NON_SME + r"(\([^)]{0,30}\))?(도|은|는|이|가)?\s*(입찰에\s*)?(참여|참가)"
    r"(가\s*(?<!불)가능(합니다|함|하다)|할\s*수\s*있(습니다|다|음))" + _END)
# 예외 **사유**가 있다는 것과 예외를 **쓴다**는 것은 다르다 — 법 제7조① 은 중소기업자간 경쟁
# 의무를 풀어 줄 뿐이다. 그래서 "제4호의 경우에 해당" 은 적용으로 읽지 않고(방법을 고른 서술이
# 아니다), 공고가 중소기업자간 경쟁입찰로 **진행한다고 적으면** 문서 어디에 있든 발화하지 않는다.
# 문구 목록이 아니라 두 가지 사실을 본다. 틀리면 놓치는 쪽이라 넓게 잡는다.
#   방법 — 중소기업자간 경쟁을 입찰 방법으로 적는다: 서술(`경쟁입찰(방식)로 진행` · `경쟁입찰을
#     실시` · `경쟁입찰 대상입니다`)이든 항목(`입찰방법 : 중소기업자간 (제한)경쟁`)이든.
#     `입찰`·`방식` 바로 뒤 조사만 보므로 "경쟁입찰 외의 방법으로" · "경쟁입찰의 방법 등으로는" ·
#     "경쟁입찰의 예외" 는 안 걸린다.
#   자격 — 중소기업·소기업·소상공인이 나오고 **같은 문장 40자 안에** 한정 표지(`만 참가` ·
#     `에 한함` · `로 제한/한정`)가 온다. 사이 말은 보지 않는다 — `중소기업확인서를 소지한
#     업체만 참가` · `중소기업(비영리 제외)에 한함` 처럼 한정을 적는 방법이 끝이 없어서다.
#     자격 항목은 표지 없이도 한정이다 — `입찰참가자격: 중소기업확인서를 소지한 자`. 항목 이름
#     바로 뒤 구분(`:` · `-` · `○` 따위 · `은/는`) 다음 값에 중소기업·소기업·소상공인이 나오면
#     본다. 항목 대신 문장으로 누가 입찰하는지 정의해도 같다 — `참가할 수 있는 자는
#     중소기업확인서를 소지한 자입니다`. `참가자격의 기업 구분과 다른 경우 - 발급된 중소기업ㆍ소상공인확인서의 …`(실격 사유
#     상용구, 발화하는 공고 다섯에 있다)는 이름 뒤가 `의` 라 안 걸린다.
# 이 거부 전체가 dev 6건 · 무라벨 910건에 걸리고, C11 이 발화하는 18건(dev 1 · 무라벨 17)과는
# 하나도 겹치지 않는다.
SME_ONLY_BID = re.compile(
    r"중소기업자\s*간\s*경쟁(\s*입찰)?\s*(방식|방법)?\s*(으로|로|을|를)\s*(진행|실시|집행|추진|시행|입찰|한다|합니다|함)"
    r"|중소기업자\s*간\s*경쟁\s*입찰\s*대상(입니다|이다|임)"
    r"|(입찰|계약|낙찰)\s*(방법|방식)\s*[:：]?\s*(\S+\s*)?중소기업자\s*간\s*(제한\s*)?경쟁"
    r"(?!\s*(입찰|제품)?\s*(의|에\s*대한|외|적용\s*제외))"
    r"|(참가\s*자격\s*(요건\s*)?([:：\-–○●□■▶◦ㅇ]|은|는)"
    r"|(참가|참여|입찰|응찰)\s*(할|하는|하려는)\s*(수\s*있는\s*)?(자|업체|기업|사업자)(는|은|의\s*자격은))"
    r"\s*[^.。※:：]{0,80}?(중소기업|소기업|소상공인)"
    r"|(중소기업|소기업|소상공인)[^.。※]{0,40}?"
    r"(만\s*(이\s*)?(입찰|참가|참여|응찰|가능|을\s*대상)|에\s*한(함|합니다|한다|하며|하여|하고|정|해)|(으)?로\s*(제한|한정))")
# 같은 효과를 부정문으로 적는 꼴 — "중소기업자간 경쟁입찰 제품에 해당하지 않음"(실제 공고
# `PPS-D-018502`). 여기서 부정은 예외를 **긍정**한다. 그래서 이 꼴의 `않` 은 `NEGATED` 로
# 보지 않고, 그 **앞**의 부정·조건만 본다.
NOT_SME_BID = re.compile(
    r"중소기업자\s*간\s*경쟁\s*입찰\s*(제품|대상)?에\s*해당하지\s*(않|아니)(음|습니다|는다|함)" + _END)
# 부정은 **예외 판단의 범위 안에서만** 본다 — 인용 끝부터 적용 서술어 끝까지. 서술어 자체의
# 부정(`적용하지 않`·`안 적용`·`미적용`·`예외 적용 불가`)은 `APPLIED` 가 애초에 안 받는다.
# 남는 것은 서술어 **앞**의 부정이다 — "예외에 해당하지 않으므로 일반 규정을 적용합니다".
# 서술어 **뒤**의 부정은 결과의 서술이다 — "적용하므로 대기업의 참여 제한이 없습니다".
# 같은 범위에서 예외를 **바꿔 치우는** 말도 본다 — `대신`("제4호 대신 …의 예외를 적용"), 그리고
# 다른 법령 인용(`「` · `법 제N` · `시행령` · `제N조`). 그 뒤의 `예외` 는 인용한 조문의 것이 아니다.
NEGATED = re.compile(r"않|아니|없|못|불가|불허|배제|[안미]\s*(적용|해당)|대신"
                     r"|「|법\s*제\s*\d|시행령|제\s*\d+\s*조")
# `예외` 도 누구의 예외인지 본다. 인용한 조문의 것(인용 바로 뒤, `제4호에 따라` 같은 연결만 끼어도
# 된다)이거나 (중소기업자간) 경쟁입찰·우선조달의 것이어야 한다 — "제4호의 경우 수의계약의 예외에
# 해당합니다" 는 아니다. 임자는 `예외` 에 **바로 붙어야** 한다(`…경쟁입찰의 예외` · `…에 대한 예외`).
# 앞 어딘가에 `중소기업자` 가 나오는 것으로는 안 된다 — "중소기업자 확인사항을 검토하고 발주기관
# 내규의 예외를 적용" 의 예외는 내규의 것이다. 실제 발화 중 `예외` 꼴 10건은 전부 뒤쪽이다.
OWN_EXCEPTION = re.compile(
    r"(((중소기업자\s*(간\s*)?)?(경쟁\s*입찰|우선\s*조달\s*(계약)?)|중소기업자\s*간\s*경쟁(\s*제도)?)"
    r"\s*(의|에\s*대한)?\s*"
    r"|^\s*((제\s*)?\d+\s*호\s*\*?\s*)?(의|에\s*(따른|따라|의한|의하여|의거한?|의거하여|근거한|근거하여))?\s*,?\s*)$")
# 서술어가 **말해진 것이 아니라 언급된 것**이면 적용이 아니다 — 서식 항목의 값("예외 적용
# (□예 ■아니오)"), 인용·삭제("…적용합니다\"라는 문구는 삭제"), 물음과 답("적용합니다? 아니오"),
# 정정·폐지("(정정 전)" · "[폐지]"), 예시("(작성 예시)"), 뒤로 미룸("(향후 공고부터)"), 일부 범위
# ("(부대장비에 한함)"), 단서("적용함, 단 해당 품목은 제외"). 이런 말을 하나씩 늘어놓지 않고
# 모양을 본다 — 서술어 **바로 뒤**에 곁말(닫는 괄호가 아닌 문장 부호로 여는 말)이 붙으면, 그 곁말이
# 예외의 **사유**를 대는 이름(`사유` · `근거` · `경우` · `필요`)일 때만 적용으로 읽는다. 이름이지
# 절이 아니어야 한다 — 부정도, 조건(`경우에` · `-면` · `때에`)도, 한정(`만`)도, 서술 어미(`-다` ·
# `-며` · `-고`)도 없어야 한다. "(사유가 확인되는 경우에만 적용하며 현재는 일반 규정을 따릅니다)" 는
# 사유를 대는 것이 아니라 적용을 미룬다. 괄호·따옴표로 열면 닫는 짝까지(80자 안), 아니면 25자를 본다.
# 서술어 바로 뒤 `여부`("적용함 여부는 …")도 곁말을 연다. 부호 없이 이어지는 결과 서술("적용하므로
# 대기업의 참여 제한이 없습니다")은 곁말이 아니다. 실제 발화 18건 중 곁말이 붙은 것은 `009599`
# 하나이고 그 곁말은 `<중소기업자간 경쟁제도 예외사유>` 다.
# 예외가 공고의 **일부**에만 걸리면 셀을 닫지 않는다 — "부대장비는 중소기업자간 경쟁입찰 제품에
# 해당하지 않음" · "2권역에 대해서는 … 예외를 적용합니다". 인용과 서술어 사이에 주제(`X는` ·
# `X에는` · `X에 대해서는`)가 서면 그 X 에만 걸린 말이다. X 가 공고 전체(`본 물품` · `이 입찰` ·
# `해당 사업` …)이면 괜찮다. `해당하는` · `되는` 같은 관형형은 주제가 아니다. 실제 발화 18건의
# 인용 뒤에는 주제가 하나도 없다. 한정(`부대장비에만` · `2권역만` · `…에 한하여`)도 같다.
TOPIC = re.compile(r"[가-힣]+((?<![하되있없않])는|은|에는|에\s*대해서는|에\s*대하여는"
                   r"|에만|(?<!지)만|에\s*한(하여|정하여|해서?))(?=[\s,])")
WHOLE_NOTICE = re.compile(r"(본|이|해당|당해)\s*(입찰|물품|사업|용역|계약|공고|구매|건|과업)\S*$")


def partial_scope(head: str) -> bool:
    """인용과 서술어 사이(`head`)에 공고 전체가 아닌 주제가 서는가."""
    return any(WHOLE_NOTICE.search(head[:topic.start(1)]) is None for topic in TOPIC.finditer(head))


# 서술어 **뒤**에서는 `는`·`은` 이 범위를 좁히지 않는다. 거기서는 그냥 뒤 절의 주어다 —
# "적용하여 입찰참가자는 별도 서류를 낼 수 있다" · "적용하여 많은 업체가 참여할 수 있다".
# 그래서 꼬리에서는 **한정 표지만** 센다. 뜻이 오직 좁히는 것뿐인 어미들이다.
LIMITER = re.compile(r"[가-힣0-9]+(에만|(?<!지)만|에\s*한(하여|정하여|해서?)"
                     r"|에\s*대해서는|에\s*대하여는)(?=[\s,])")


def narrowed_after(rest: str) -> bool:
    """서술어 뒤(`rest`)에서 적용 범위를 좁히는 한정이 서는가."""
    return any(WHOLE_NOTICE.search(rest[:limit.start(1)]) is None for limit in LIMITER.finditer(rest))


ASIDE = re.compile(r"\s*(여부|[^\s가-힣0-9A-Za-z.)\]}>」』])")
REASON = re.compile(r"사유|근거|경우|필요")
ASIDE_NEGATIVE = re.compile(r"아니|없|미\s*(해당|적용)|비해당|삭제|정정|취소|철회|폐지|제외"
                            r"|(?<![가-힣A-Za-z])([Xx×]|N|No|NO)(?![A-Za-z])")
ASIDE_CLAUSE = re.compile(r"경우\s*에|때\s*(에|만|는)|(?<=[가-힣])면(?![가-힣])|(?<!지)만(?![가-힣])"
                          r"|다(?![가-힣])|(하|되|으|이|있|없)(며|고)(?![가-힣])")
PAIRS = {"(": ")", "[": "]", "<": ">", "「": "」", "『": "』", "“": "”", '"': '"', "'": "'"}


def aside_withdraws(clause: str, end: int) -> bool:
    """서술어 끝(`end`) 바로 뒤 곁말이 그 서술을 언급·철회·한정으로 바꾸는가."""
    opened = ASIDE.match(clause, end)
    if opened is None:
        return False
    close = PAIRS.get(opened.group(1))
    if close is not None and close in clause[opened.end():opened.end() + 80]:
        aside = clause[opened.end():clause.index(close, opened.end())]
    else:
        aside = clause[opened.end():opened.end() + 25]
    return (REASON.search(aside) is None or ASIDE_NEGATIVE.search(aside) is not None
            or ASIDE_CLAUSE.search(aside) is not None)


# 곁말을 받아들였다고 문장이 끝난 것이 아니다. 그 뒤에서 같은 적용을 거두어들일 수 있다 —
# "제4호를 적용합니다(사유: …), 그러나 본 공고에는 적용하지 않습니다". `NEGATED` 는 서술어
# **앞**만 보고 `aside_withdraws` 는 곁말 **안**만 보므로, 그 사이로 이 꼴이 빠져나갔다.
# 좁게 잡는다 — 서술어 뒤에서 `적용·해당`이 **바로** 부정되는 경우만 철회로 읽는다. 결과의
# 서술("적용하므로 … 제한이 없습니다")은 `적용`에 부정이 안 붙으므로 안 걸린다.
RETRACTED = re.compile(r"(적용|해당)(하지|되지|치)?\s*(않|아니|못)|[미비]\s*적용"
                       r"|적용\s*(제외|배제|불가|안\s*함)")


def retracted_after(clause: str, end: int) -> bool:
    """서술어 끝(`end`) 뒤에서 그 적용을 거두어들이는가."""
    return RETRACTED.search(clause[end:]) is not None


SENTENCE = 160


